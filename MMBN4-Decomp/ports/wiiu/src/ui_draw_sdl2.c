static void sdl2_clear(void* ctx, UiColor c) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderClear(r);
}

static void sdl2_rect(void* ctx, int x, int y, int w, int h, UiColor c) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    SDL_Rect rc = { x, y, w, h };
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderFillRect(r, &rc);
}

static void sdl2_rect_outline(void* ctx, int x, int y, int w, int h, UiColor c) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    SDL_Rect rc = { x, y, w, h };
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderDrawRect(r, &rc);
}

static void sdl2_line(void* ctx, int x1, int y1, int x2, int y2, UiColor c) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    SDL_RenderDrawLine(r, x1, y1, x2, y2);
}

static void sdl2_text(void* ctx, int x, int y, const char* s, UiColor c) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    for (int cx = x; *s; ++s, cx += 8) {
        int ch = toupper((unsigned char) *s);
        if (ch < 0x20 || ch > 0x5F) continue;
        const uint8_t* g = FONT5X7[ch - 0x20];
        for (int row = 0; row < 7; ++row) {
            uint8_t bits = g[row];
            for (int col = 0; col < 5; ++col) {
                if (bits & (0x10u >> col)) {
                    SDL_RenderDrawPoint(r, cx + col, y + row);
                }
            }
        }
    }
}

static void sdl2_clip(void* ctx, int x, int y, int w, int h) {
    SDL_Renderer* r = (SDL_Renderer*) ctx;
    if (w <= 0 || h <= 0) {
        SDL_RenderSetClipRect(r, NULL);
    } else {
        SDL_Rect rc = { x, y, w, h };
        SDL_RenderSetClipRect(r, &rc);
    }
}

UiDraw ui_draw_sdl2(SDL_Renderer* renderer) {
    UiDraw ui;
    ui.ctx          = renderer;
    ui.clear        = sdl2_clear;
    ui.rect         = sdl2_rect;
    ui.rect_outline = sdl2_rect_outline;
    ui.line         = sdl2_line;
    ui.text         = sdl2_text;
    ui.clip         = sdl2_clip;
    return ui;
}
