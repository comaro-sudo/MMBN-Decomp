#!/usr/bin/env python3
"""Generate rom.s from config/segments_<v>.toml.

    python3 tools/split.py [rs|bm]

Segments are emitted in address order; every gap becomes
`.incbin "baserom.gba", off, size`, so the ROM always rebuilds whole.
"""
from __future__ import annotations

import sys
import tomllib
from pathlib import Path

DECOMP = Path(__file__).resolve().parents[1]
BASE = 0x08000000


def load(v: str) -> dict:
    cfg = tomllib.loads((DECOMP / "config" / f"segments_{v}.toml").read_text())
    segs = sorted(cfg.get("segment", []), key=lambda s: s["start"])
    prev = BASE
    for s in segs:
        if s["start"] < prev:
            sys.exit(f"segment {s['name']} overlaps the previous one")
        if s["end"] <= s["start"]:
            sys.exit(f"segment {s['name']} is empty")
        prev = s["end"]
    cfg["segment"] = segs
    return cfg


def incbin(start: int, end: int) -> str:
    return f'    .incbin "baserom.gba", 0x{start - BASE:X}, 0x{end - start:X}   @ 0x{start:08X}-0x{end:08X}\n'


def main() -> None:
    v = sys.argv[1] if len(sys.argv) > 1 else "rs"
    cfg = load(v)
    rom_end = BASE + cfg["rom_size"]
    out = ["@ GENERATED by tools/split.py from config/segments_%s.toml - do not edit.\n" % v,
           "    .syntax unified\n",
           '    .section .rom, "ax"\n\n']
    cur = BASE
    for s in cfg["segment"]:
        if s["start"] > cur:
            out.append(incbin(cur, s["start"]))
        if s["kind"] == "code" and not (DECOMP / "asm" / f"{s['name']}.s").exists():
            out.append(incbin(s["start"], s["end"]).rstrip("\n") + f"   (asm/{s['name']}.s not generated yet)\n")
        elif s["kind"] in ("header", "code"):
            out.append(f'    .include "asm/{s["name"]}.s"              @ 0x{s["start"]:08X}-0x{s["end"]:08X}\n')
        elif s["kind"] == "incbin":
            out.append(incbin(s["start"], s["end"]))
        else:
            sys.exit(f"unknown kind {s['kind']}")
        cur = s["end"]
    if cur < rom_end:
        out.append(incbin(cur, rom_end))
    out.append('\n    .include "externs.inc"   @ build/<v>/externs.inc, from tools/split.py\n')
    (DECOMP / "rom.s").write_text("".join(out), newline="\n")
    n = write_externs(v)
    print(f"rom.s: {len(cfg['segment'])} segments, rest incbin; {n} extern function symbols")


def write_externs(v: str) -> int:
    """Define every known function not yet carved as a section-relative symbol.

    `.thumb_set sub_X, Start + off` keeps calls inside one section, so `as`
    resolves BL offsets itself: no relocations, no linker interworking stubs.
    """
    import re
    defined = set()
    for f in (DECOMP / "asm").glob("*.s"):
        defined |= set(re.findall(r"^(sub_[0-9A-F]{8}):", f.read_text(), re.M))
    lines = ["@ GENERATED by tools/split.py: functions still inside incbin ranges"]
    src = DECOMP / "symbols" / f"functions_{v}.txt"
    for line in src.read_text().splitlines():
        if line.startswith("#"):
            continue
        a, mode, *_ = line.split()
        name = f"sub_{a.upper()}"
        if name in defined:
            continue
        off = int(a, 16) - BASE
        lines.append(f"    {'.thumb_set' if mode == 'T' else '.set'} {name}, Start + 0x{off:X}")
    out = DECOMP / "build" / v / "externs.inc"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", newline="\n")
    return len(lines) - 1


if __name__ == "__main__":
    main()
