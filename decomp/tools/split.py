#!/usr/bin/env python3
"""Generate build/<v>/rom.s and build/<v>/externs.inc.

    python3 tools/split.py [rs|bm]

Red Sun and Blue Moon have independent address layouts while their insertion
points are still being identified. RS source lives in asm/ and Blue Moon's
parallel generated source lives in asm/bm/. Both use the same generator and
the same source tree; identical functions can be merged only after both
variants assemble and compare cleanly.
"""
from __future__ import annotations

import re
import sys
import tomllib
from pathlib import Path

DECOMP = Path(__file__).resolve().parents[1]
BASE = 0x08000000


def load(v: str) -> dict:
    cfg = tomllib.loads((DECOMP / "config" / f"segments_{v}.toml").read_text())
    segs = sorted(cfg.get("segment", []), key=lambda s: s["start"])
    prev = BASE
    for s in segs:
        if s["start"] < prev:
            sys.exit(f"segment {s['name']} overlaps the previous one")
        if s["end"] <= s["start"]:
            sys.exit(f"segment {s['name']} is empty")
        prev = s["end"]
    cfg["segment"] = segs
    return cfg


def incbin(start: int, end: int) -> str:
    return f'    .incbin "baserom.gba", 0x{start - BASE:X}, 0x{end - start:X}   @ 0x{start:08X}-0x{end:08X}\n'


def main() -> None:
    v = sys.argv[1] if len(sys.argv) > 1 else "rs"
    cfg = load(v)
    rom_end = BASE + cfg["rom_size"]
    out = [f"@ GENERATED by tools/split.py from config/segments_{v}.toml - do not edit.\n",
           f"@ {v.upper()} layout; assembles only this version's address space.\n",
           "    .syntax unified\n",
           '    .include "include/macros.inc"\n',
           '    .section .rom, "ax"\n\n']
    cur = BASE
    for s in cfg["segment"]:
        if s["start"] > cur:
            out.append(incbin(cur, s["start"]))
        # The cartridge header is shared: it only branches into crt0 and
        # reads the remaining per-ROM bytes directly.  Generated code is
        # version-addressed once the ROM layouts diverge.
        shared = s["kind"] == "header"
        asm = DECOMP / "asm" / ("" if shared or v == "rs" else v) / f"{s['name']}.s"
        asm_rel = f"asm/{s['name']}.s" if shared or v == "rs" else f"asm/{v}/{s['name']}.s"
        if s["kind"] == "code" and not asm.exists():
            out.append(f"    .set SEG_BM_DELTA, 0x0\n")
            out.append(f"    incrom 0x{s['start'] - BASE:X}, 0x{s['end'] - s['start']:X}   "
                       f"@ {asm_rel} not generated yet\n")
        elif s["kind"] in ("header", "code"):
            out.append(f'    .include "{asm_rel}"              @ 0x{s["start"]:08X}-0x{s["end"]:08X}\n')
        else:
            sys.exit(f"unknown kind {s['kind']}")
        cur = s["end"]
    if cur < rom_end:
        out += ["\n@ Data region (graphics, maps, text, music): still incbin.\n",
                incbin(cur, rom_end)]
    out.append('\n    .include "externs.inc"   @ build/<v>/externs.inc, from tools/split.py\n')
    out.append('    .include "symbols.inc"   @ build/<v>/symbols.inc, canonical symbol aliases\n')
    out_path = DECOMP / "build" / v / "rom.s"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("".join(out), newline="\n")
    # Keep the historical top-level source as a convenient, inspectable copy
    # of the default (Red Sun) layout. The Makefile always assembles the
    # versioned file above, so a Blue Moon build cannot overwrite it.
    if v == "rs":
        (DECOMP / "rom.s").write_text("".join(out), newline="\n")
    n = write_externs(v)
    nsym = write_symbol_aliases(v)
    print(f"{out_path.relative_to(DECOMP)}: {len(cfg['segment'])} segments; externs: {n}; symbols: {nsym}")


def write_externs(v: str) -> int:
    """Symbols for functions/data references that have no label in asm/*.s.

    Section-relative (`Start + off`) so `as` resolves BL offsets itself (no
    relocations or interworking stubs). Names use their source version's
    original address.
    """
    asm_dir = DECOMP / "asm" / ("" if v == "rs" else v)
    text = "".join(f.read_text() for f in asm_dir.glob("*.s"))
    defined = set(re.findall(r"^((?:sub|dat)_[0-9A-F]{8}):", text, re.M))
    emitted = set(defined)
    lines = [f"@ GENERATED by tools/split.py for {v.upper()}: symbols without a label in asm/"]

    for line in (DECOMP / "symbols" / f"functions_{v}.txt").read_text().splitlines():
        if line.startswith("#"):
            continue
        a, mode, *_ = line.split()
        name = f"sub_{a.upper()}"
        if name not in emitted:
            emitted.add(name)
            lines.append(f"    {'.thumb_set' if mode == 'T' else '.set'} {name}, Start + 0x{int(a, 16) - BASE:X}")
    dfile = DECOMP / "symbols" / f"datarefs_{v}.txt"
    if dfile.exists():
        for tok in dfile.read_text().split():
            if not re.fullmatch(r"[0-9A-Fa-f]{8}", tok):
                continue
            name = f"dat_{tok.upper()}"
            if name not in emitted:
                emitted.add(name)
                lines.append(f"    .set {name}, Start + 0x{int(tok, 16) - BASE:X}")
    for name in sorted(set(re.findall(r"\b((?:sub|dat)_[0-9A-F]{8})\b", text)) - emitted):
        addr = int(name[4:], 16)
        if BASE <= addr < BASE + 0x800000:
            lines.append(f"    {'.thumb_set' if name.startswith('sub_') else '.set'} {name}, Start + 0x{addr - BASE:X}")
    out = DECOMP / "build" / v / "externs.inc"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", newline="\n")
    return len(lines) - 1


def write_symbol_aliases(v: str) -> int:
    """Generate canonical symbol aliases for ELF / C / ASM builds.
    Produces build/<v>/symbols.inc with .global and .set definitions.
    """
    names_file = DECOMP / "symbols" / "names.txt"
    if not names_file.exists():
        return 0
    lines = [f"@ GENERATED by tools/split.py for {v.upper()}: canonical symbol aliases"]
    count = 0
    for line in names_file.read_text().splitlines():
        if line.startswith("#") or not line.strip():
            continue
        parts = line.split()
        if len(parts) < 5:
            continue
        addr_rs, addr_bm, kind, source, name = parts[0], parts[1], parts[2], parts[3], parts[4]
        addr_hex = addr_rs if v == "rs" else addr_bm
        try:
            addr = int(addr_hex, 16)
        except ValueError:
            continue
        lines.append(f"    .global {name}")
        if addr >= BASE:
            if kind == "code":
                lines.append(f"    .thumb_set {name}, Start + 0x{addr - BASE:X}")
            else:
                lines.append(f"    .set {name}, Start + 0x{addr - BASE:X}")
        else:
            lines.append(f"    .set {name}, 0x{addr:08X}")
        count += 1
    out = DECOMP / "build" / v / "symbols.inc"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", newline="\n")
    return count


if __name__ == "__main__":
    main()
