#!/usr/bin/env python3
"""Write a compact Markdown report of unresolved indirect-control-flow sites.

    ~/.venvs/mmbn4-decomp/bin/python tools/dispatch.py rs [code_05]

The report is evidence for DC-2 work; it does not change symbols or source.
"""
from __future__ import annotations

import argparse
import tomllib
from pathlib import Path

from capstone import CS_ARCH_ARM, CS_MODE_ARM, CS_MODE_THUMB, Cs

import survey as sv

DECOMP = Path(__file__).resolve().parents[1]


def segments(version: str) -> dict[str, tuple[int, int]]:
    cfg = tomllib.loads((DECOMP / "config" / f"segments_{version}.toml").read_text())
    return {s["name"]: (s["start"], s["end"]) for s in cfg["segment"]}


def standard_survey(version: str) -> sv.Survey:
    rom = sv.Rom(sv.ROMS[version])
    s = sv.Survey(rom)
    s.code_end = 0x08120000
    ins = next(s.arm.disasm(rom.d[:4], sv.BASE))
    s.seed(sv.imm_target(ins.op_str), False, "entry")
    s.run()
    if version == "rs":
        for address, _ in sv.ce_code_symbols():
            s.seed(address | 1, True, "ce")
        s.run()
    s.pointer_tables()
    s.run()
    s.short_prologue_pointer_tables()
    s.run()
    s.prologue_pass()
    return s


def containing_segment(layout: dict[str, tuple[int, int]], address: int) -> str:
    for name, (start, end) in layout.items():
        if start <= address < end:
            return name
    return "outside configured code"


def context(s: sv.Survey, address: int) -> str:
    """Disassemble the stopping instruction and its two predecessors."""
    thumb = s.thumb
    out = []
    for a in range(address - 4, address + 2, 2):
        if not s.rom.in_rom(a):
            continue
        insn = next(thumb.disasm(s.rom.d[a - sv.BASE:a - sv.BASE + 4], a), None)
        if insn is not None:
            marker = " =>" if a == address else "   "
            out.append(f"{marker} `0x{a:08X}: {insn.mnemonic} {insn.op_str}`")
    return "<br>".join(out)


def origins(s: sv.Survey, kind: str, address: int) -> str:
    """Show the discovered function entries that reached an unresolved site."""
    values = []
    for start in sorted(s.unresolved_origins[kind][address]):
        info = s.funcs[start]
        values.append(f"`0x{start:08X}` ({info['source']}, clean={int(info['ok'])})")
    return "<br>".join(values)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("version", choices=sv.ROMS)
    ap.add_argument("segment", nargs="?", help="restrict output to one configured segment")
    args = ap.parse_args()

    layout = segments(args.version)
    if args.segment and args.segment not in layout:
        ap.error(f"unknown segment {args.segment}")
    s = standard_survey(args.version)
    selected = layout.get(args.segment) if args.segment else None
    title = args.segment or "all code segments"
    lines = [
        f"# DC-2 indirect-dispatch report: {args.version.upper()} {title}",
        "",
        "Generated by `tools/dispatch.py`; do not treat a listed site as a proven jump table.",
        "",
    ]
    for kind in ("jump_table_or_pc_write", "bx_reg", "bx_call"):
        sites = sorted(s.unresolved_sites[kind])
        if selected:
            lo, hi = selected
            sites = [a for a in sites if lo <= a < hi]
        lines += [f"## {kind}", "", f"Distinct sites: {len(sites)}", ""]
        if not sites:
            continue
        lines += ["| Segment | Site and nearby Thumb decode | Survey origin(s) |", "|---|---|---|"]
        for address in sites:
            lines.append(f"| `{containing_segment(layout, address)}` | {context(s, address)} | "
                         f"{origins(s, kind, address)} |")
        lines.append("")
    out = DECOMP / "notes" / f"dc2-dispatch-{args.version}-{args.segment or 'all'}.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(DECOMP)}")


if __name__ == "__main__":
    main()
